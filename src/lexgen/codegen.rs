//! Code generation for table-driven lexers.

use crate::error::Result;
use crate::lexgen::dfa::Dfa;
use crate::lexgen::nfa::Nfa;
use crate::lexgen::rules::{LexerSpec, RuleAction};
use std::collections::HashMap;

pub enum TargetLanguage {
    C,
    Java,
    Python,
}

/// Returns true if the spec uses advanced features that require the full codegen path.
/// When false, we can use the minimal generator for much shorter output (~90 lines).
fn spec_needs_advanced(spec: &LexerSpec) -> bool {
    // Multiple start conditions
    if spec.start_conditions.len() > 1 {
        return true;
    }
    // Any Code actions (REJECT, yymore, yyless, etc.)
    for rule in &spec.rules {
        if matches!(&rule.action, RuleAction::Code(_)) {
            return true;
        }
        if matches!(&rule.action, RuleAction::Begin(_) | RuleAction::TokenAndBegin(_, _)) {
            return true;
        }
    }
    false
}

/// Generates a minimal C lexer â€” under 100 lines for simple specs.
/// Only emits what's strictly needed: token enum, struct, transition switch, next_token, test driver.
fn generate_c_minimal(dfa: &crate::lexgen::dfa::Dfa, spec: &LexerSpec) -> Result<String> {
    let mut c = String::new();

    // Header â€” JSCPP-compatible, no pointer arithmetic or compound literals
    c.push_str("/* Lexer generated by OpenLexer */\n");
    c.push_str("#include <stdio.h>\n");
    c.push_str("#include <string.h>\n\n");

    // Token type constants as #define (avoids typedef enum issues in JSCPP)
    c.push_str("#define TOKEN_EOF 0\n");
    c.push_str("#define TOKEN_ERROR 1\n");
    let mut seen = std::collections::HashSet::new();
    seen.insert("EOF".to_string());
    seen.insert("ERROR".to_string());
    let mut token_id = 2;
    for rule in &spec.rules {
        if let RuleAction::Token(name) = &rule.action {
            let upper = name.to_uppercase();
            if seen.insert(upper.clone()) {
                c.push_str(&format!("#define TOKEN_{} {}\n", upper, token_id));
                token_id += 1;
            }
        }
    }
    c.push_str("\n");

    // Global state â€” avoids struct pointers that JSCPP can't handle
    c.push_str("char src[4096];\n");
    c.push_str("int pos;\n");
    c.push_str("int tok_type;\n");
    c.push_str("int tok_start;\n");
    c.push_str("int tok_len;\n\n");

    // Transition function â€” compact switch (unchanged, this works in JSCPP)
    c.push_str("int transition(int state, int ch) {\n");
    c.push_str("    switch (state) {\n");
    for state in &dfa.states {
        let has_transitions = !state.range_transitions.is_empty() || !state.transitions.is_empty();
        if !has_transitions {
            continue;
        }
        c.push_str(&format!("    case {}:", state.id));
        if !state.range_transitions.is_empty() {
            for &(start_cp, end_cp, target) in &state.range_transitions {
                if start_cp == end_cp {
                    c.push_str(&format!(
                        " if(ch=={}) return {};",
                        escape_c_char(char::from_u32(start_cp).unwrap_or('?')),
                        target
                    ));
                } else {
                    c.push_str(&format!(
                        " if(ch>={} && ch<={}) return {};",
                        escape_c_char(char::from_u32(start_cp).unwrap_or('?')),
                        escape_c_char(char::from_u32(end_cp).unwrap_or('?')),
                        target
                    ));
                }
            }
            c.push_str(" return -1;\n");
        } else {
            for (ch, target) in &state.transitions {
                c.push_str(&format!(" if(ch=={}) return {};", escape_c_char(*ch), target));
            }
            c.push_str(" return -1;\n");
        }
    }
    c.push_str("    default: return -1;\n    }\n}\n\n");

    // Accepting function
    c.push_str("int accepting(int state) {\n    switch(state) {\n");
    for state in &dfa.states {
        if state.is_accepting {
            if let Some(rule_idx) = state.rule_index {
                c.push_str(&format!("    case {}: return {};\n", state.id, rule_idx));
            }
        }
    }
    c.push_str("    default: return -1;\n    }\n}\n\n");

    // Token name helper
    c.push_str("const char* token_name(int type) {\n    switch(type) {\n");
    c.push_str("    case TOKEN_EOF: return \"EOF\";\n");
    c.push_str("    case TOKEN_ERROR: return \"ERROR\";\n");
    
    let mut displayed_tokens = std::collections::HashSet::new();
    displayed_tokens.insert("EOF".to_string());
    displayed_tokens.insert("ERROR".to_string());
    
    for rule in &spec.rules {
        if let RuleAction::Token(name) = &rule.action {
            let upper = name.to_uppercase();
            if displayed_tokens.insert(upper.clone()) {
                c.push_str(&format!("    case TOKEN_{}: return \"{}\";\n", upper, upper));
            }
        }
    }
    c.push_str("    default: return \"UNKNOWN\";\n    }\n}\n\n");

    // Rule action mapping
    c.push_str("int rule_token(int rule) {\n    switch(rule) {\n");
    for (idx, rule) in spec.rules.iter().enumerate() {
        match &rule.action {
            RuleAction::Token(name) => {
                c.push_str(&format!("    case {}: return TOKEN_{};\n", idx, name.to_uppercase()));
            }
            RuleAction::Skip => {
                c.push_str(&format!("    case {}: return -1;\n", idx));
            }
            RuleAction::Error => {
                c.push_str(&format!("    case {}: return TOKEN_ERROR;\n", idx));
            }
            _ => {}
        }
    }
    c.push_str("    default: return TOKEN_ERROR;\n    }\n}\n\n");

    // next_token — sets global tok_type, tok_start, tok_len (no struct return)
    c.push_str("void lexer_next() {\n");
    c.push_str("    int start, state, last_rule, last_pos, ns, r, tok;\n");
    c.push_str("    while (src[pos] != 0) {\n");
    c.push_str("        start = pos; state = 0; last_rule = -1; last_pos = start;\n");
    c.push_str("        while (src[pos] != 0) {\n");
    c.push_str("            ns = transition(state, src[pos]);\n");
    c.push_str("            if (ns < 0) break;\n");
    c.push_str("            state = ns; pos = pos + 1;\n");
    c.push_str("            r = accepting(state);\n");
    c.push_str("            if (r >= 0) { last_rule = r; last_pos = pos; }\n");
    c.push_str("        }\n");
    c.push_str("        if (last_rule >= 0) {\n");
    c.push_str("            pos = last_pos;\n");
    c.push_str("            tok = rule_token(last_rule);\n");
    c.push_str("            if (tok < 0) continue;\n");
    c.push_str("            tok_type = tok; tok_start = start; tok_len = last_pos - start;\n");
    c.push_str("            return;\n");
    c.push_str("        }\n");
    c.push_str("        pos = start + 1;\n");
    c.push_str("        tok_type = TOKEN_ERROR; tok_start = start; tok_len = 1;\n");
    c.push_str("        return;\n");
    c.push_str("    }\n");
    c.push_str("    tok_type = TOKEN_EOF; tok_start = pos; tok_len = 0;\n");
    c.push_str("}\n\n");

    // Test driver
    c.push_str("#ifndef LEXER_NO_TEST\n");
    c.push_str("void test(const char input[]) {\n");
    c.push_str("    int i;\n");
    c.push_str("    printf(\"Input: \\\"%s\\\"\\n\", input);\n");
    c.push_str("    if (strlen(input) >= 4096) { printf(\"Input too long\\n\"); return; }\n");
    c.push_str("    strcpy(src, input);\n");
    c.push_str("    pos = 0;\n");
    c.push_str("    do {\n");
    c.push_str("        lexer_next();\n");
    c.push_str("        printf(\"  %-12s | \\\"\", token_name(tok_type));\n");
    c.push_str("        for(i = 0; i < tok_len; i = i + 1) {\n");
    c.push_str("            printf(\"%c\", src[tok_start + i]);\n");
    c.push_str("        }\n");
    c.push_str("        printf(\"\\\"\\n\");\n");
    c.push_str("    } while(tok_type != TOKEN_EOF);\n");
    c.push_str("}\n");
    c.push_str("#endif\n\n");
    c.push_str("#ifndef LEXER_NO_MAIN\n");
    c.push_str("int main(int argc, char** argv) {\n");
    c.push_str("    if (argc > 1) {\n");
    c.push_str("        int i;\n");
    c.push_str("        for (i = 1; i < argc; i++) test(argv[i]);\n");
    c.push_str("    } else {\n");
    c.push_str("        char line[4096];\n");
    c.push_str("        if (fgets(line, sizeof(line), stdin)) {\n");
    c.push_str("            int len = strlen(line);\n");
    c.push_str("            if (len > 0 && line[len-1] == '\\n') line[len-1] = 0;\n");
    c.push_str("            test(line);\n");
    c.push_str("        } else {\n");
    c.push_str("            test(\"3 + 4 * 2\");\n");
    c.push_str("        }\n");
    c.push_str("    }\n");
    c.push_str("    return 0;\n");
    c.push_str("}\n");
    c.push_str("#endif\n");

    Ok(c)
}


/// Generates a minimal Python lexer â€” compact output for simple specs.
fn generate_python_minimal(dfa: &crate::lexgen::dfa::Dfa, spec: &LexerSpec) -> Result<String> {
    let mut c = String::new();

    c.push_str("\"\"\"Lexer generated by OpenLexer\"\"\"\n\n");

    // Token constants
    c.push_str("TOKEN_EOF, TOKEN_ERROR = 0, 1\n");
    let mut seen = std::collections::HashSet::new();
    seen.insert("EOF".to_string());
    seen.insert("ERROR".to_string());
    let mut next_id = 2;
    for rule in &spec.rules {
        if let RuleAction::Token(name) = &rule.action {
            let upper = name.to_uppercase();
            if seen.insert(upper.clone()) {
                c.push_str(&format!("TOKEN_{} = {}\n", upper, next_id));
                next_id += 1;
            }
        }
    }

    // Token names for display
    c.push_str("\nTOKEN_NAMES = {TOKEN_EOF: 'EOF', TOKEN_ERROR: 'ERROR'");
    for rule in &spec.rules {
        if let RuleAction::Token(name) = &rule.action {
            let upper = name.to_uppercase();
            c.push_str(&format!(", TOKEN_{}: '{}'", upper, upper));
        }
    }
    c.push_str("}\n\n");

    // Transition table as dict
    c.push_str("_TRANS = {\n");
    for state in &dfa.states {
        let has_trans = !state.range_transitions.is_empty() || !state.transitions.is_empty();
        if !has_trans { continue; }
        c.push_str(&format!("    {}: [", state.id));
        if !state.range_transitions.is_empty() {
            for &(start_cp, end_cp, target) in &state.range_transitions {
                c.push_str(&format!("({},{},{}),", start_cp, end_cp, target));
            }
        } else {
            for (ch, target) in &state.transitions {
                let cp = *ch as u32;
                c.push_str(&format!("({},{},{}),", cp, cp, target));
            }
        }
        c.push_str("],\n");
    }
    c.push_str("}\n\n");

    // Accepting table
    c.push_str("_ACCEPT = {");
    for state in &dfa.states {
        if state.is_accepting {
            if let Some(rule_idx) = state.rule_index {
                c.push_str(&format!("{}: {},", state.id, rule_idx));
            }
        }
    }
    c.push_str("}\n\n");

    // Rule to token mapping
    c.push_str("_RULE_TOKEN = {");
    for (idx, rule) in spec.rules.iter().enumerate() {
        match &rule.action {
            RuleAction::Token(name) => c.push_str(&format!("{}: TOKEN_{},", idx, name.to_uppercase())),
            RuleAction::Skip => c.push_str(&format!("{}: None,", idx)),
            RuleAction::Error => c.push_str(&format!("{}: TOKEN_ERROR,", idx)),
            _ => {}
        }
    }
    c.push_str("}\n\n");

    // Lexer class
    c.push_str("class Lexer:\n");
    c.push_str("    def __init__(self, src): self.src, self.pos = src, 0\n\n");
    c.push_str("    def next_token(self):\n");
    c.push_str("        while self.pos < len(self.src):\n");
    c.push_str("            start, state, last_rule, last_pos = self.pos, 0, -1, self.pos\n");
    c.push_str("            while self.pos < len(self.src):\n");
    c.push_str("                cp, ns = ord(self.src[self.pos]), -1\n");
    c.push_str("                for lo, hi, tgt in _TRANS.get(state, []):\n");
    c.push_str("                    if lo <= cp <= hi: ns = tgt; break\n");
    c.push_str("                if ns < 0: break\n");
    c.push_str("                state = ns; self.pos += 1\n");
    c.push_str("                if state in _ACCEPT: last_rule, last_pos = _ACCEPT[state], self.pos\n");
    c.push_str("            if last_rule >= 0:\n");
    c.push_str("                self.pos = last_pos\n");
    c.push_str("                tok = _RULE_TOKEN.get(last_rule, TOKEN_ERROR)\n");
    c.push_str("                if tok is None: continue\n");
    c.push_str("                return (tok, self.src[start:last_pos])\n");
    c.push_str("            self.pos = start + 1\n");
    c.push_str("            return (TOKEN_ERROR, self.src[start:start+1])\n");
    c.push_str("        return (TOKEN_EOF, '')\n\n");

    c.push_str("    def tokenize(self):\n");
    c.push_str("        while True:\n");
    c.push_str("            tok = self.next_token()\n");
    c.push_str("            yield tok\n");
    c.push_str("            if tok[0] == TOKEN_EOF: break\n\n");

    // Test
    c.push_str("def test(text):\n");
    c.push_str("    print(f'Input: \"{text}\"')\n");
    c.push_str("    for tok, val in Lexer(text).tokenize():\n");
    c.push_str("        print(f'  [{TOKEN_NAMES.get(tok, tok)}] \"{val}\"')\n\n");
    c.push_str("if __name__ == '__main__':\n");
    c.push_str("    import sys\n");
    c.push_str("    if len(sys.argv) > 1:\n");
    c.push_str("        for arg in sys.argv[1:]: test(arg)\n");
    c.push_str("    else:\n");
    c.push_str("        import sys as _sys\n");
    c.push_str("        _input = _sys.stdin.read().strip()\n");
    c.push_str("        if _input:\n");
    c.push_str("            for line in _input.splitlines(): test(line)\n");
    c.push_str("        else: test('3 + 4 * 2'); test('(10 - 2) / 4')\n");

    Ok(c)
}

/// Generates a minimal Java lexer â€” compact output for simple specs.
fn generate_java_minimal(dfa: &crate::lexgen::dfa::Dfa, spec: &LexerSpec) -> Result<String> {
    let mut c = String::new();

    c.push_str("/** Lexer generated by OpenLexer */\n");
    c.push_str("class Lexer {\n");

    // Token constants
    c.push_str("    public static final int TOKEN_EOF = 0, TOKEN_ERROR = 1");
    let mut seen = std::collections::HashSet::new();
    seen.insert("EOF".to_string());
    seen.insert("ERROR".to_string());
    let mut next_id = 2;
    for rule in &spec.rules {
        if let RuleAction::Token(name) = &rule.action {
            let upper = name.to_uppercase();
            if seen.insert(upper.clone()) {
                c.push_str(&format!(", TOKEN_{} = {}", upper, next_id));
                next_id += 1;
            }
        }
    }
    c.push_str(";\n\n");
    c.push_str("    private static final String[] TOKEN_NAMES = new String[] {\"TOKEN_EOF\", \"TOKEN_ERROR\"");
    
    // Generate token names array for lookup
    let mut seen_names = std::collections::HashSet::new();
    seen_names.insert("EOF".to_string());
    seen_names.insert("ERROR".to_string());
    
    for rule in &spec.rules {
        if let RuleAction::Token(name) = &rule.action {
            let upper = name.to_uppercase();
            if seen_names.insert(upper.clone()) {
                c.push_str(&format!(", \"TOKEN_{}\"", upper));
            }
        }
    }
    c.push_str("};\n\n");
    c.push_str("    public static String tokenName(int token) {\n");
    c.push_str("        if (token >= 0 && token < TOKEN_NAMES.length) return TOKEN_NAMES[token];\n");
    c.push_str("        return \"UNKNOWN\";\n");
    c.push_str("    }\n\n");

    c.push_str("    private String src; private int pos;\n");
    c.push_str("    public Lexer(String s) { src = s; pos = 0; }\n\n");

    // Transition
    c.push_str("    private int transition(int state, char c) {\n");
    c.push_str("        switch (state) {\n");
    for state in &dfa.states {
        let has_trans = !state.range_transitions.is_empty() || !state.transitions.is_empty();
        if !has_trans { continue; }
        c.push_str(&format!("        case {}:", state.id));
        if !state.range_transitions.is_empty() {
            for &(start_cp, end_cp, target) in &state.range_transitions {
                if start_cp == end_cp {
                    c.push_str(&format!(" if(c=={}) return {};", start_cp, target));
                } else {
                    c.push_str(&format!(" if(c>={} && c<={}) return {};", start_cp, end_cp, target));
                }
            }
            c.push_str(" return -1;\n");
        } else {
            for (ch, target) in &state.transitions {
                c.push_str(&format!(" if(c=={}) return {};", *ch as u32, target));
            }
            c.push_str(" return -1;\n");
        }
    }
    c.push_str("        default: return -1;\n        }\n    }\n\n");

    // Accepting
    c.push_str("    private int accepting(int state) {\n        switch(state) {\n");
    for state in &dfa.states {
        if state.is_accepting {
            if let Some(rule_idx) = state.rule_index {
                c.push_str(&format!("        case {}: return {};\n", state.id, rule_idx));
            }
        }
    }
    c.push_str("        default: return -1;\n        }\n    }\n\n");

    // Rule token
    c.push_str("    private int ruleToken(int rule) {\n        switch(rule) {\n");
    for (idx, rule) in spec.rules.iter().enumerate() {
        match &rule.action {
            RuleAction::Token(name) => c.push_str(&format!("        case {}: return TOKEN_{};\n", idx, name.to_uppercase())),
            RuleAction::Skip => c.push_str(&format!("        case {}: return -1;\n", idx)),
            RuleAction::Error => c.push_str(&format!("        case {}: return TOKEN_ERROR;\n", idx)),
            _ => {}
        }
    }
    c.push_str("        default: return TOKEN_ERROR;\n        }\n    }\n\n");

    // Token class for lexer-parser integration
    c.push_str("    public static class Token {\n");
    c.push_str("        public final int type;\n");
    c.push_str("        public final String text;\n");
    c.push_str("        public final int pos;\n");
    c.push_str("        public Token(int type, String text, int pos) {\n");
    c.push_str("            this.type = type; this.text = text; this.pos = pos;\n");
    c.push_str("        }\n");
    c.push_str("    }\n\n");

    // nextToken - returns Token object for parser compatibility
    c.push_str("    public Token nextToken() {\n");
    c.push_str("        while (pos < src.length()) {\n");
    c.push_str("            int start = pos, state = 0, lastRule = -1, lastPos = start;\n");
    c.push_str("            while (pos < src.length()) {\n");
    c.push_str("                int ns = transition(state, src.charAt(pos));\n");
    c.push_str("                if (ns < 0) break;\n");
    c.push_str("                state = ns; pos++;\n");
    c.push_str("                int r = accepting(state);\n");
    c.push_str("                if (r >= 0) { lastRule = r; lastPos = pos; }\n");
    c.push_str("            }\n");
    c.push_str("            if (lastRule >= 0) {\n");
    c.push_str("                pos = lastPos;\n");
    c.push_str("                int tok = ruleToken(lastRule);\n");
    c.push_str("                if (tok < 0) continue;\n");
    c.push_str("                return new Token(tok, src.substring(start, lastPos), start);\n");
    c.push_str("            }\n");
    c.push_str("            pos = start + 1;\n");
    c.push_str("            return new Token(TOKEN_ERROR, src.substring(start, start+1), start);\n");
    c.push_str("        }\n");
    c.push_str("        return new Token(TOKEN_EOF, \"\", pos);\n");
    c.push_str("    }\n\n");

    // Main
    c.push_str("    public static void main(String[] args) {\n");
    c.push_str("        String[] inputs;\n");
    c.push_str("        if (args.length > 0) {\n");
    c.push_str("            inputs = args;\n");
    c.push_str("        } else {\n");
    c.push_str("            try {\n");
    c.push_str("                java.util.Scanner sc = new java.util.Scanner(System.in);\n");
    c.push_str("                java.util.List<String> lines = new java.util.ArrayList<>();\n");
    c.push_str("                while (sc.hasNextLine()) { String l = sc.nextLine().trim(); if (!l.isEmpty()) lines.add(l); }\n");
    c.push_str("                inputs = lines.isEmpty() ? new String[]{\"3 + 4 * 2\"} : lines.toArray(new String[0]);\n");
    c.push_str("            } catch (Exception e) { inputs = new String[]{\"3 + 4 * 2\"}; }\n");
    c.push_str("        }\n");
    c.push_str("        for (String inp : inputs) {\n");
    c.push_str("            System.out.println(\"Input: \\\"\" + inp + \"\\\"\");\n");
    c.push_str("            Lexer l = new Lexer(inp); Token t;\n");
    c.push_str("            do { t = l.nextToken();\n");
    c.push_str("                System.out.println(\"  \" + String.format(\"%-12s\", tokenName(t.type)) + \" | \\\"\" + t.text + \"\\\"\");\n");
    c.push_str("            } while (t.type != TOKEN_EOF);\n");
    c.push_str("        }\n");
    c.push_str("    }\n");
    c.push_str("}\n");

    Ok(c)
}

/// Generates a lexer from a DFA (legacy single-pattern mode).
pub fn generate_lexer(dfa: &Dfa, lang: TargetLanguage) -> Result<String> {
    match lang {
        TargetLanguage::C => generate_c_simple(dfa),
        TargetLanguage::Java => generate_java_simple(dfa),
        TargetLanguage::Python => generate_python_simple(dfa),
    }
}

/// Generates a full lexer from a lexer specification with start conditions.
/// Builds separate DFAs for each start condition for optimal performance.
/// Automatically uses minimal output (~90 lines) for simple specs.
pub fn generate_lexer_from_spec_with_conditions(
    spec: &LexerSpec,
    lang: TargetLanguage,
) -> Result<String> {
    // Auto-detect: use minimal generator for simple specs (no advanced features)
    if !spec_needs_advanced(spec) {
        let nfa = Nfa::from_lexer_spec_for_condition(spec, "INITIAL")?;
        let dfa = Dfa::from_nfa(&nfa)?;
        return match lang {
            TargetLanguage::C => generate_c_minimal(&dfa, spec),
            TargetLanguage::Java => generate_java_minimal(&dfa, spec),
            TargetLanguage::Python => generate_python_minimal(&dfa, spec),
        };
    }

    // Build DFAs for each start condition
    let mut dfas: HashMap<String, Dfa> = HashMap::new();

    for condition in spec.start_conditions.keys() {
        let nfa = Nfa::from_lexer_spec_for_condition(spec, condition)?;
        let dfa = Dfa::from_nfa(&nfa)?;
        dfas.insert(condition.clone(), dfa);
    }

    match lang {
        TargetLanguage::C => generate_c_with_conditions(&dfas, spec),
        TargetLanguage::Java => generate_java_with_conditions(&dfas, spec),
        TargetLanguage::Python => generate_python_with_conditions(&dfas, spec),
    }
}

/// Generates a full lexer from a DFA and lexer specification (multi-token mode).
/// Legacy API - does not support start conditions properly.
pub fn generate_lexer_from_spec(
    dfa: &Dfa,
    spec: &LexerSpec,
    lang: TargetLanguage,
) -> Result<String> {
    // Auto-detect: use minimal generator for simple specs
    if !spec_needs_advanced(spec) {
        return match lang {
            TargetLanguage::C => generate_c_minimal(dfa, spec),
            TargetLanguage::Java => generate_java_minimal(dfa, spec),
            TargetLanguage::Python => generate_python_minimal(dfa, spec),
        };
    }

    // If spec has only INITIAL condition, use the simple path
    if spec.start_conditions.len() <= 1 {
        match lang {
            TargetLanguage::C => generate_c_full(dfa, spec),
            TargetLanguage::Java => generate_java_full(dfa, spec),
            TargetLanguage::Python => generate_python_full(dfa, spec),
        }
    } else {
        // Use the new condition-aware generator
        generate_lexer_from_spec_with_conditions(spec, lang)
    }
}

